# Measures which of Mix's own modules are loaded before the first
# dependency's compile runs any package code, on each way a user compiles a
# dependency, with the `elixir` and `mix` on PATH (one toolchain per run).
# Writes `<pair>.txt` beside this script, `<pair>` the toolchain as the
# builders name it (`1.20-29`): a header, then the intersection over the
# paths, one module per line. NccWorker.Tracer.MixBase embeds every such
# file; the tracer takes a module of that list as loaded for the user too
# (otp-probe round 4, ruling on R2-6).
#
#     elixir apps/ncc_worker/priv/mix_base/measure.exs
#
# The paths, each from a fresh build:
#   * `mix compile` in a new project with one dependency;
#   * `mix deps.compile` in the same project;
#   * `Mix.install([dep])` in an `elixir -e` script.
# Livebook's runtime is not measured (see the header the script writes).
#
# The one dependency records the loaded modules at the earliest point
# package code can run in its compile: an Erlang parse transform the
# `erlang` compiler runs before Elixir's (`erl_first_files`), and again in
# an Elixir module body. A path's set is the intersection of its two
# records; the list is the intersection over the paths, of the modules of
# Mix's own application.

tmp = Path.join(System.tmp_dir!(), "ncc-mix-base-#{System.unique_integer([:positive])}")
File.mkdir_p!(tmp)
dep = Path.join(tmp, "ncc_mix_base_rec")
File.mkdir_p!(Path.join(dep, "lib"))
File.mkdir_p!(Path.join(dep, "src"))

File.write!(Path.join(dep, "mix.exs"), """
defmodule NccMixBaseRec.MixProject do
  use Mix.Project

  def project,
    do: [app: :ncc_mix_base_rec, version: "0.1.0", erlc_options: [], erl_first_files: ["src/ncc_mix_base_pt.erl"], deps: []]
end
""")

File.write!(Path.join([dep, "src", "ncc_mix_base_pt.erl"]), """
-module(ncc_mix_base_pt).
-export([parse_transform/2]).

parse_transform(Forms, _Options) ->
    Out = os:getenv("NCC_MIX_BASE_OUT"),
    Names = [atom_to_list(M) || {M, _} <- code:all_loaded()],
    ok = file:write_file(Out ++ ".erl", lists:join("\\n", Names)),
    Forms.
""")

File.write!(Path.join([dep, "src", "ncc_mix_base_user.erl"]), """
-module(ncc_mix_base_user).
-compile({parse_transform, ncc_mix_base_pt}).
-export([f/0]).

f() -> ok.
""")

File.write!(Path.join([dep, "lib", "ncc_mix_base_rec.ex"]), """
defmodule NccMixBaseRec do
  File.write!(
    System.fetch_env!("NCC_MIX_BASE_OUT") <> ".ex",
    Enum.map_join(:code.all_loaded(), "\\n", &Atom.to_string(elem(&1, 0)))
  )

  def f, do: :ok
end
""")

proj = Path.join(tmp, "proj")
File.mkdir_p!(proj)

File.write!(Path.join(proj, "mix.exs"), """
defmodule NccMixBaseProj.MixProject do
  use Mix.Project

  def project, do: [app: :ncc_mix_base_proj, version: "0.1.0", deps: [{:ncc_mix_base_rec, path: #{inspect(dep)}}]]
end
""")

env = fn out -> [{"NCC_MIX_BASE_OUT", out}, {"MIX_ENV", "dev"}, {"MIX_INSTALL_DIR", Path.join(tmp, "installs")}] end

record = fn name, run ->
  out = Path.join(tmp, name)
  {log, status} = run.(env.(out))
  if status != 0, do: raise("#{name} failed (#{status}):\n#{log}")

  sets =
    for ext <- [".erl", ".ex"],
        do: (out <> ext) |> File.read!() |> String.split("\n", trim: true) |> MapSet.new()

  {name, Enum.reduce(sets, &MapSet.intersection/2)}
end

fresh = fn -> File.rm_rf!(Path.join(proj, "_build")) end

paths = [
  record.("mix compile", fn env ->
    fresh.()
    System.cmd("mix", ["compile"], cd: proj, env: env, stderr_to_stdout: true)
  end),
  record.("mix deps.compile", fn env ->
    fresh.()
    System.cmd("mix", ["deps.compile"], cd: proj, env: env, stderr_to_stdout: true)
  end),
  record.("Mix.install", fn env ->
    script = "Mix.install([{:ncc_mix_base_rec, path: #{inspect(dep)}}], force: true)"
    System.cmd("elixir", ["-e", script], cd: tmp, env: env, stderr_to_stdout: true)
  end)
]

:ok = Application.load(:mix)
mix = :mix |> Application.spec(:modules) |> MapSet.new(&Atom.to_string/1)
base = paths |> Enum.map(&elem(&1, 1)) |> Enum.reduce(&MapSet.intersection/2) |> MapSet.intersection(mix)

[major, minor | _] = String.split(System.version(), ".")
otp = System.otp_release()
pair = "#{major}.#{minor}-#{otp}"
otp_full = :code.root_dir() |> Path.join(["releases/", otp, "/OTP_VERSION"]) |> File.read!() |> String.trim()

header =
  [
    "# Mix modules loaded before the first dependency's compile runs package code,",
    "# on every path below (intersection). Generated by measure.exs; do not edit.",
    "# toolchain: Elixir #{System.version()}, OTP #{otp_full}",
    for({name, set} <- paths, do: "# path #{name}: #{set |> MapSet.intersection(mix) |> MapSet.size()} Mix modules"),
    "# not measured: Livebook's runtime (Mix.install in a remote evaluator)",
    "# modules: #{MapSet.size(base)}"
  ]
  |> List.flatten()

file = Path.join(__DIR__, "#{pair}.txt")
File.write!(file, Enum.join(header ++ Enum.sort(base), "\n") <> "\n")
File.rm_rf!(tmp)
IO.puts("#{file}: #{MapSet.size(base)} modules (#{Enum.map_join(paths, ", ", fn {n, s} -> "#{n} #{s |> MapSet.intersection(mix) |> MapSet.size()}" end)})")
