# Measures which modules every way a user compiles a dependency has loaded
# by the earliest point package code runs: the evaluation of the first
# dependency's mix.exs (otp-probe round 5, R3-4 and R3-8), with the `elixir`
# and `mix` on PATH (one toolchain per run). Writes `<pair>.txt` beside this
# script, `<pair>` the toolchain as the builders name it (`1.20-29`): a
# header, then the intersection over the paths, one module per line.
# NccWorker.Tracer.MixBase embeds every such file; the tracer takes a module
# of that list, loaded before it started, as loaded for the user too.
#
#     elixir apps/ncc_worker/priv/mix_base/measure.exs
#
# The paths, each from a fresh build:
#   * `mix compile` in a new project with one dependency;
#   * `mix deps.compile` in the same project;
#   * `Mix.install([dep])` in an `elixir -e` script.
# Livebook's runtime is not measured (see the header the script writes).
#
# The one dependency's mix.exs records the loaded modules the first time it
# is evaluated, before its project/0 is asked for anything: every module,
# not only Mix's (Process, String, Version, ...).

tmp = Path.join(System.tmp_dir!(), "ncc-mix-base-#{System.unique_integer([:positive])}")
File.mkdir_p!(tmp)
dep = Path.join(tmp, "ncc_mix_base_rec")
File.mkdir_p!(Path.join(dep, "lib"))

File.write!(Path.join(dep, "mix.exs"), """
out = System.fetch_env!("NCC_MIX_BASE_OUT")

unless File.exists?(out) do
  File.write!(out, Enum.map_join(:code.all_loaded(), "\\n", &Atom.to_string(elem(&1, 0))))
end

defmodule NccMixBaseRec.MixProject do
  use Mix.Project

  def project, do: [app: :ncc_mix_base_rec, version: "0.1.0", deps: []]
end
""")

File.write!(Path.join([dep, "lib", "ncc_mix_base_rec.ex"]), """
defmodule NccMixBaseRec do
  def f, do: :ok
end
""")

proj = Path.join(tmp, "proj")
File.mkdir_p!(proj)

File.write!(Path.join(proj, "mix.exs"), """
defmodule NccMixBaseProj.MixProject do
  use Mix.Project

  def project, do: [app: :ncc_mix_base_proj, version: "0.1.0", deps: [{:ncc_mix_base_rec, path: #{inspect(dep)}}]]
end
""")

env = fn out -> [{"NCC_MIX_BASE_OUT", out}, {"MIX_ENV", "dev"}, {"MIX_INSTALL_DIR", Path.join(tmp, "installs")}] end

record = fn name, run ->
  out = Path.join(tmp, name)
  {log, status} = run.(env.(out))
  if status != 0, do: raise("#{name} failed (#{status}):\n#{log}")

  {name, out |> File.read!() |> String.split("\n", trim: true) |> MapSet.new()}
end

fresh = fn -> File.rm_rf!(Path.join(proj, "_build")) end

paths = [
  record.("mix compile", fn env ->
    fresh.()
    System.cmd("mix", ["compile"], cd: proj, env: env, stderr_to_stdout: true)
  end),
  record.("mix deps.compile", fn env ->
    fresh.()
    System.cmd("mix", ["deps.compile"], cd: proj, env: env, stderr_to_stdout: true)
  end),
  record.("Mix.install", fn env ->
    script = "Mix.install([{:ncc_mix_base_rec, path: #{inspect(dep)}}], force: true)"
    System.cmd("elixir", ["-e", script], cd: tmp, env: env, stderr_to_stdout: true)
  end)
]

:ok = Application.load(:mix)
mix = :mix |> Application.spec(:modules) |> MapSet.new(&Atom.to_string/1)
base = paths |> Enum.map(&elem(&1, 1)) |> Enum.reduce(&MapSet.intersection/2)

[major, minor | _] = String.split(System.version(), ".")
otp = System.otp_release()
pair = "#{major}.#{minor}-#{otp}"
otp_full = :code.root_dir() |> Path.join(["releases/", otp, "/OTP_VERSION"]) |> File.read!() |> String.trim()

header =
  [
    "# Modules loaded when the first dependency's mix.exs is evaluated, on every",
    "# path below (intersection). Generated by measure.exs; do not edit.",
    "# toolchain: Elixir #{System.version()}, OTP #{otp_full}",
    for({name, set} <- paths, do: "# path #{name}: #{MapSet.size(set)} modules (#{set |> MapSet.intersection(mix) |> MapSet.size()} Mix)"),
    "# not measured: Livebook's runtime (Mix.install in a remote evaluator)",
    "# modules: #{MapSet.size(base)} (#{base |> MapSet.intersection(mix) |> MapSet.size()} Mix)"
  ]
  |> List.flatten()

file = Path.join(__DIR__, "#{pair}.txt")
File.write!(file, Enum.join(header ++ Enum.sort(base), "\n") <> "\n")
File.rm_rf!(tmp)
IO.puts("#{file}: #{MapSet.size(base)} modules (#{Enum.map_join(paths, ", ", fn {n, s} -> "#{n} #{MapSet.size(s)}" end)})")
