defmodule Portal.Precompiled.Manifests do
  @moduledoc """
  Manifests as bytes. A batch names the SHA-256 of each package's manifest,
  so the manifest a client receives must be the bytes that were hashed, not
  a fresh render. Rendered by a batch when the package's inputs changed
  (`Portal.Precompiled.Batches`), stored in `Portal.ArtifactStore` by hash,
  served from there.
  """
  alias Portal.{ArtifactStore, Catalog}

  @spec render(String.t()) :: {:ok, binary()} | :none
  def render(package_name), do: package_name |> Catalog.precompiled_manifest() |> encode()

  @doc "The format-2 manifest (`Portal.Catalog.precompiled_manifest_v2/1`) as bytes."
  @spec render_v2(String.t()) :: {:ok, binary()} | :none
  def render_v2(package_name), do: package_name |> Catalog.precompiled_manifest_v2() |> encode()

  @doc """
  Both formats from one load of the package's catalog data, the same bytes
  `render/1` and `render_v2/1` give, and the package's stored shas this host
  lacked (`Portal.Catalog.precompiled_manifests/1`).
  """
  @spec render_both(String.t()) :: %{
          v1: {:ok, binary()} | :none,
          v2: {:ok, binary()} | :none,
          absent: [String.t()]
        }
  def render_both(package_name) do
    %{v1: v1, v2: v2, absent: absent} = Catalog.precompiled_manifests(package_name)
    %{v1: encode(v1), v2: encode(v2), absent: absent}
  end

  defp encode(nil), do: :none
  defp encode(manifest), do: {:ok, JSON.encode!(manifest)}

  @doc """
  Stores `bytes` under their SHA-256 and returns it. A blob that already holds
  exactly these bytes is left as it is; any other blob under that name is
  replaced.
  """
  @spec store(binary()) :: {:ok, String.t()} | {:error, term()}
  def store(bytes) do
    sha = sha256(bytes)
    if read(sha) == {:ok, bytes}, do: {:ok, sha}, else: put(sha, bytes)
  end

  @doc "The bytes stored under `sha`, only when they hash to it."
  @spec read_intact(String.t()) :: {:ok, binary()} | :error
  def read_intact(sha) do
    with {:ok, bytes} <- read(sha),
         true <- sha256(bytes) == sha do
      {:ok, bytes}
    else
      _ -> :error
    end
  end

  @doc "Whether the store holds bytes under `sha` that hash to it."
  @spec intact?(String.t()) :: boolean()
  def intact?(sha), do: match?({:ok, _}, read_intact(sha))

  defp sha256(bytes), do: Base.encode16(:crypto.hash(:sha256, bytes), case: :lower)

  # sobelow_skip ["Traversal.FileModule"]
  # Temporary file path is generated by the module; sha is calculated from the payload.
  defp put(sha, bytes) do
    tmp = Path.join(System.tmp_dir!(), "manifest-#{sha}-#{System.unique_integer([:positive])}")

    # `after`, not `rescue`: the staging file goes whatever the put does,
    # including an exit or throw. A put that succeeded has moved it already.
    try do
      with :ok <- File.write(tmp, bytes),
           {:ok, _} <- ArtifactStore.put(sha, tmp) do
        {:ok, sha}
      end
    after
      cleanup_tmp(tmp)
    end
  end

  @spec read(String.t()) :: {:ok, binary()} | :error
  # sobelow_skip ["Traversal.FileModule"]
  # Path comes from ArtifactStore.blob_path of a sha validated by ArtifactStore.present?.
  def read(sha) do
    if ArtifactStore.present?(sha),
      do: File.read(ArtifactStore.blob_path(sha)) |> ok_or_error(),
      else: :error
  end

  # sobelow_skip ["Traversal.FileModule"]
  # Path is a temporary file created and named by this module.
  defp cleanup_tmp(path) do
    _ = File.rm(path)
    :ok
  end

  defp ok_or_error({:ok, bin}), do: {:ok, bin}
  defp ok_or_error(_), do: :error
end
